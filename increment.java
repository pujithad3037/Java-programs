class increment
{
    public static void main(String[] args)
    {
        int a=10;
        System.out.println("post increment = "+(a++));
        //System.out.println(a);
        System.out.println("Pre increment = "+(++a));
        //System.out.println(a);
        System.out.println("post decrement = "+(a--));
        //System.out.println(a);
        System.out.println("pre decrement = "+(--a));
        
    }
}